def blocks(doc):
    for child in doc.element.body.iterchildren():
        if child.tag == qn("w:p"):
            yield Paragraph(child, doc)
        elif child.tag == qn("w:tbl"):
            yield Table(child, doc)


def all_paragraphs(doc):
    for block in blocks(doc):
        if isinstance(block, Paragraph):
            yield block
        else:
            for row in block.rows:
                for cell in row.cells:
                    for paragraph in cell.paragraphs:
                        yield paragraph


def set_text(paragraph, text):
    runs = paragraph.runs
    if not runs:
        paragraph.add_run(text)
        return
    runs[0].text = text
    for run in runs[1:]:
        run.text = ""


def apply_fix(doc, old, new, expect, note):
    hits = [p for p in all_paragraphs(doc) if old in p.text]
    if len(hits) != expect:
        raise SystemExit(f"[中止] {note}：应命中 {expect} 处，实际 {len(hits)} 处 -> {old[:34]}")
    for p in hits:
        set_text(p, p.text.replace(old, new))
    print(f"  × {len(hits)}  {note}")


def apply_cell_label(doc, label, new, note):
    hits = [p for p in all_paragraphs(doc) if p.text.strip() == label]
    if len(hits) != 1:
        raise SystemExit(f"[中止] {note}：整格「{label}」应 1 处，实际 {len(hits)} 处")
    set_text(hits[0], new)
    print(f"  整格  {note}")


def insert_after(doc, anchor, texts, note):
    hits = [p for p in all_paragraphs(doc) if anchor in p.text]
    if len(hits) != 1:
        raise SystemExit(f"[中止] 插入锚点应 1 处，实际 {len(hits)}：{note} | {anchor[:30]}")
    base = hits[0]
    previous = base
    for text in texts:
        new_p = copy.deepcopy(base._p)
        for tag in ("w:bookmarkStart", "w:bookmarkEnd"):
            for node in new_p.findall(qn(tag)):
                new_p.remove(node)
        previous._p.addnext(new_p)
        paragraph = Paragraph(new_p, base._parent)
        set_text(paragraph, text)
        previous = paragraph
    print(f"  插入 × {len(texts)}  {note}")


def main():
    apply = "--apply" in sys.argv
    doc = Document(str(DOCX))
    print(f"读入 {DOCX.name}")
    for old, new, expect, note in FIXES:
        apply_fix(doc, old, new, expect, note)
    for label, new, note in CELL_LABELS:
        apply_cell_label(doc, label, new, note)
    for anchor, texts, note in INSERTS:
        insert_after(doc, anchor, texts, note)
    if not apply:
        print("演练通过：加 --apply 才真写。")
        return
    stamp = time.strftime("%Y%m%d_%H%M")
    bak = BAK_DIR / f"storybook_backup_{stamp}.docx"
    shutil.copy2(DOCX, bak)
    print(f"备份 -> {bak}")
    doc.save(str(DOCX))
    print(f"已写回 {DOCX}")


if __name__ == "__main__":
    main()
