def all_paragraphs(doc):
    for child in doc.element.body.iterchildren():
        if child.tag == qn("w:p"):
            yield Paragraph(child, doc)
        elif child.tag == qn("w:tbl"):
            tbl = Table(child, doc)
            for row in tbl.rows:
                for cell in row.cells:
                    for p in cell.paragraphs:
                        yield p


def set_text(p, text):
    runs = p.runs
    if not runs:
        p.add_run(text)
        return
    runs[0].text = text
    for r in runs[1:]:
        r.text = ""


def main():
    apply = "--apply" in sys.argv
    doc = Document(str(DOCX))
    paras = list(all_paragraphs(doc))
    for old, new, expect, note in FIXES:
        hits = [p for p in paras if old in p.text]
        if len(hits) != expect:
            raise SystemExit(f"[中止] {note}：应 {expect} 处，实际 {len(hits)} -> {old[:34]}")
        if old != new:
            for p in hits:
                set_text(p, p.text.replace(old, new))
            print(f"  × {len(hits)}  {note}")
        else:
            print(f"  不动  {note}")
    if not apply:
        print("演练通过：加 --apply 才真写。")
        return
    stamp = time.strftime("%Y%m%d_%H%M")
    bak = BAK_DIR / f"storybook_backup_{stamp}.docx"
    shutil.copy2(DOCX, bak)
    print(f"备份 -> {bak}")
    doc.save(str(DOCX))
    print(f"已写回 {DOCX}")


if __name__ == "__main__":
    main()
